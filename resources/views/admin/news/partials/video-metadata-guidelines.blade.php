{{-- Lieferanten-Vorgaben Videos / Metadaten (redaktioneller Hinweis) --}}
<div class="rounded-xl border border-sky-200 bg-sky-50/80 p-4 text-sm text-sky-950 min-w-0">
    <p class="font-semibold text-sky-950">METADATEN (Lieferanten)</p>
    <ol class="mt-2 list-decimal list-inside space-y-2 text-sky-900/95">
        <li>Bei vielen Lieferanten sind die Metadaten <strong>im Videomaterial</strong> enthalten – das ist die <strong>favorisierte Variante</strong>.</li>
        <li>Alternativ: Metadaten in einer <strong>separaten XMP-Datei</strong>. Der Dateiname muss zum Video passen, z.&nbsp;B.:
            <ul class="mt-1 ml-4 list-disc list-inside font-mono text-xs text-sky-900">
                <li>videosnippet_01012019.mp4</li>
                <li>videosnippet_01012019.xmp</li>
            </ul>
        </li>
    </ol>
    <p class="mt-3 text-sky-900/95">
        Metadaten sollten enthalten: <strong>Caption</strong>, <strong>Ort</strong>, <strong>Datum</strong>, <strong>Keywords</strong>.
        Es sollen nur <strong>textbasierte</strong> Metadaten-Dateien geliefert werden (keine proprietären Formate wie Microsoft Office oder LibreOffice).
    </p>
    <p class="mt-2 text-xs text-sky-800/90">
        Für die automatische Bereitstellung müssen diese Vorgaben eingehalten werden. Unten pflegt die Redaktion die Metadaten pro Video in der Datenbank (ergänzend zu Datei/XMP).
    </p>
</div>
